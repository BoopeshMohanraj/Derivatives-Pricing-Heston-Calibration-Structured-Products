# ── Delta Hedging Simulation Function ─────────────────────────
def delta_hedge_simulation(stock_path, K, r, sigma, T, n_steps,
                            option_type="call"):
    """
    Simulate delta hedging a short call/put position.

    Setup: Short 1 option. Hold Delta shares to hedge.
    Rebalance at each step. Finance at risk-free rate.

    Parameters
    ----------
    stock_path  : array — Simulated stock prices (length n_steps+1)
    K           : float — Strike
    r           : float — Risk-free rate
    sigma       : float — Volatility
    T           : float — Total time to expiry (years)
    n_steps     : int   — Number of rebalancing steps
    option_type : str   — 'call' or 'put'

    Returns
    -------
    df : DataFrame — Full rebalancing table
    hedging_error : float — Final P&L of hedge portfolio
    """
    dt        = T / n_steps
    records   = []
    cash      = 0.0     # Cash account (borrowing/lending)
    delta_old = 0.0

    for i in range(n_steps + 1):
        t_remaining = T - i * dt
        S_i         = stock_path[i]

        # Greeks at this step
        price_i, _, _ = bsm_price(S_i, K, max(t_remaining, 1e-6),
                                   r, sigma, option_type)
        greeks_i      = compute_greeks(S_i, K, max(t_remaining, 1e-6),
                                       r, sigma, option_type)
        delta_i       = greeks_i["Delta"]
        gamma_i       = greeks_i["Gamma"]

        if i == 0:
            # Initial setup: sell option, buy delta shares
            option_sold = price_i
            shares_held = delta_i
            cash        = option_sold - shares_held * S_i
        else:
            # Accrue interest on cash
            cash = cash * np.exp(r * dt)

            # Rebalance: buy/sell (delta_i - delta_old) shares
            shares_change = delta_i - delta_old
            cash         -= shares_change * S_i
            shares_held   = delta_i

        # Gamma P&L approximation: ½·Gamma·ΔS²
        delta_S   = stock_path[i] - stock_path[i-1] if i > 0 else 0
        gamma_pnl = 0.5 * gamma_i * delta_S**2 if i > 0 else 0

        records.append({
            "Step"       : i,
            "Stock Price": round(S_i, 4),
            "T-remaining": round(t_remaining, 4),
            "Option Price": round(price_i, 4),
            "Delta"      : round(delta_i, 4),
            "Δ Shares"   : round(delta_i - delta_old, 4),
            "Cash"       : round(cash, 4),
            "Gamma"      : round(gamma_i, 4),
            "Gamma P&L"  : round(gamma_pnl, 4),
        })
        delta_old = delta_i

    df = pd.DataFrame(records)

    # Final hedge portfolio value
    final_S           = stock_path[-1]
    final_option, _,_ = bsm_price(final_S, K, 1e-6, r, sigma, option_type)
    portfolio_value   = df.iloc[-1]["Delta"] * final_S + df.iloc[-1]["Cash"]
    hedging_error     = portfolio_value - final_option

    return df, hedging_error


