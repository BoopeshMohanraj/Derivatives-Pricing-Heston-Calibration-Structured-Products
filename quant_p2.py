# ── Core Replication Functions ────────────────────────────────
def zcb_cost(notional, r, T):
    return notional * np.exp(-r * T)

def cd_participation(notional, r, T, S, K, sigma):
    """
    Participation rate as fraction of index return.
    $1,000 = ZCB_cost + participation_rate × Call_cost_per_$1_notional
    participation_rate = (notional - ZCB) / (notional × call_price/S)

    Returns participation as a decimal (e.g. 0.30 = 30%)
    """
    zcb       = zcb_cost(notional, r, T)
    budget    = notional - zcb
    call_p, _, _ = bsm_price(S, K, T, r, sigma, "call")
    # Number of calls = budget / call_price
    # Each call gives 1 unit of index = S dollars of exposure
    # Participation = n_calls * S / notional
    n_calls   = budget / call_p
    part_rate = n_calls * S / notional   # As fraction of notional
    return part_rate, zcb, budget, call_p, n_calls


