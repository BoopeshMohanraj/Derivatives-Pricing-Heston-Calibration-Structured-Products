# CELL 1: CRR Binomial Tree Engine
# Cox, Ross & Rubinstein (1979)
# ════════════════════════════════════════════════════════════════

def binomial_price(S, K, T, r, sigma, N, option_type="call", style="european", barrier=None):
    """
    CRR Binomial Tree pricer.

    Parameters
    ----------
    S           : float  — Spot price
    K           : float  — Strike price
    T           : float  — Time to expiry (years)
    r           : float  — Risk-free rate (decimal)
    sigma       : float  — Volatility (decimal)
    N           : int    — Number of time steps
    option_type : str    — 'call' or 'put'
    style       : str    — 'european', 'american', or 'barrier'
    barrier     : float  — Knock-out level (only used if style='barrier')

    Returns
    -------
    price : float — Option price
    """
    dt = T / N                                  # Length of each time step
    u  = np.exp(sigma * np.sqrt(dt))            # Up factor
    d  = 1.0 / u                                # Down factor (CRR: d = 1/u)
    q  = (np.exp(r * dt) - d) / (u - d)        # Risk-neutral probability
    df = np.exp(-r * dt)                        # One-step discount factor

    # ── Build terminal stock prices ───────────────────────────
    # At step N: S * u^j * d^(N-j) for j = 0,1,...,N
    j       = np.arange(N + 1)
    S_T     = S * (u ** j) * (d ** (N - j))

    # ── Terminal payoffs ──────────────────────────────────────
    if option_type == "call":
        V = np.maximum(S_T - K, 0.0)
    else:
        V = np.maximum(K - S_T, 0.0)

    # ── Knock-out barrier: zero out nodes above barrier ───────
    if style == "barrier" and barrier is not None:
        V[S_T >= barrier] = 0.0

    # ── Backward induction ────────────────────────────────────
    for i in range(N - 1, -1, -1):
        # Stock prices at this step
        S_i = S * (u ** np.arange(i + 1)) * (d ** (i - np.arange(i + 1)))

        # Discounted expected value
        V = df * (q * V[1:i+2] + (1 - q) * V[0:i+1])

        # American early exercise
        if style == "american":
            if option_type == "call":
                intrinsic = np.maximum(S_i - K, 0.0)
            else:
                intrinsic = np.maximum(K - S_i, 0.0)
            V = np.maximum(V, intrinsic)

        # Barrier: zero out knocked-out nodes
        if style == "barrier" and barrier is not None:
            V[S_i >= barrier] = 0.0

    return float(V[0])


