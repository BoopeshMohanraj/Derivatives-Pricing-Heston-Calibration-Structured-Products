# ── Implied Volatility Extractor ──────────────────────────────
def implied_vol(market_price, S, K, T, r, option_type="call",
                vol_low=1e-4, vol_high=5.0):
    """
    Extract implied volatility via Brent's root-finding method.
    Finds σ such that BSM(σ) = market_price.
    Returns None if no solution found.
    """
    if T <= 0 or market_price <= 0:
        return None
    try:
        obj = lambda sigma: bsm_price(S, K, T, r, sigma, option_type)[0] - market_price
        if obj(vol_low) * obj(vol_high) > 0:
            return None
        iv = brentq(obj, vol_low, vol_high, xtol=1e-6, maxiter=500)
        return iv if 0.01 <= iv <= 4.0 else None
    except Exception:
        return None


