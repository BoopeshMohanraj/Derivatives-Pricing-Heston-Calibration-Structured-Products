# CELL 6: Taylor Series P&L Approximation + Visualization
# ΔP ≈ Delta·ΔS + ½·Gamma·ΔS² + Vega·Δσ(%)
# ════════════════════════════════════════════════════════════════

def taylor_pnl(greeks, delta_S, delta_sigma_pct):
    """
    Approximate option P&L using Taylor expansion.

    Parameters
    ----------
    greeks          : dict  — from compute_greeks()
    delta_S         : float — spot move in dollars
    delta_sigma_pct : float — vol move in percentage points (+1 = +1%)

    Returns
    -------
    delta_term, gamma_term, vega_term, total : floats
    """
    delta_term = greeks["Delta"] * delta_S
    gamma_term = 0.5 * greeks["Gamma"] * delta_S**2
    vega_term  = greeks["Vega"] * delta_sigma_pct
    total      = delta_term + gamma_term + vega_term
    return delta_term, gamma_term, vega_term, total


