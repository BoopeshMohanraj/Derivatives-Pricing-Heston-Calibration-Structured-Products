def compute_greeks(S, K, T, r, sigma, option_type="call"):
    """
    Compute all five Greeks analytically.
    Vega  → per 1% vol move
    Theta → per calendar day
    Rho   → per 1% rate move
    """
    if T <= 0:
        return {g: 0.0 for g in ["Delta", "Gamma", "Vega", "Theta", "Rho"]}

    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    n_d1 = norm.pdf(d1)
    N_d1 = norm.cdf(d1)
    N_d2 = norm.cdf(d2)

    # Delta
    delta = N_d1 if option_type == "call" else N_d1 - 1.0

    # Gamma — identical for call and put
    gamma = n_d1 / (S * sigma * np.sqrt(T))

    # Vega — identical for call and put — per 1% vol move
    vega = S * n_d1 * np.sqrt(T) / 100.0

    # Theta — per calendar day
    common = -(S * n_d1 * sigma) / (2.0 * np.sqrt(T))
    if option_type == "call":
        theta = (common - r * K * np.exp(-r * T) * N_d2) / 365.0
    else:
        theta = (common + r * K * np.exp(-r * T) * norm.cdf(-d2)) / 365.0

    # Rho — per 1% rate move
    if option_type == "call":
        rho = K * T * np.exp(-r * T) * N_d2 / 100.0
    else:
        rho = -K * T * np.exp(-r * T) * norm.cdf(-d2) / 100.0

    return {"Delta": delta, "Gamma": gamma, "Vega": vega,
            "Theta": theta, "Rho": rho}


