# ── CRR Binomial Tree Engine ──────────────────────────────────
def binomial_price(S, K, T, r, sigma, N,
                   option_type="call",
                   style="european",
                   barrier=None):
    """
    CRR Binomial Tree pricer from first principles.
    Cox, Ross & Rubinstein (1979)

    Parameters
    ----------
    S, K        : float — Spot and strike
    T           : float — Time to expiry (years)
    r           : float — Risk-free rate (decimal)
    sigma       : float — Volatility (decimal)
    N           : int   — Number of time steps
    option_type : str   — 'call' or 'put'
    style       : str   — 'european', 'american', 'barrier'
    barrier     : float — Knock-out level (barrier only)

    Returns
    -------
    price : float
    """
    dt = T / N
    u  = np.exp(sigma * np.sqrt(dt))       # Up factor
    d  = 1.0 / u                           # Down factor (CRR: d=1/u)
    q  = (np.exp(r * dt) - d) / (u - d)   # Risk-neutral probability
    df = np.exp(-r * dt)                   # One-step discount factor

    # Terminal stock prices: S * u^j * d^(N-j)
    j   = np.arange(N + 1)
    S_T = S * (u**j) * (d**(N - j))

    # Terminal payoffs
    if option_type == "call":
        V = np.maximum(S_T - K, 0.0)
    else:
        V = np.maximum(K - S_T, 0.0)

    # Knock-out at terminal nodes
    if style == "barrier" and barrier is not None:
        V[S_T >= barrier] = 0.0

    # Backward induction
    for i in range(N - 1, -1, -1):
        S_i = S * (u**np.arange(i+1)) * (d**(i - np.arange(i+1)))
        V   = df * (q * V[1:i+2] + (1-q) * V[0:i+1])

        if style == "american":
            intrinsic = (np.maximum(S_i-K, 0.0) if option_type=="call"
                         else np.maximum(K-S_i, 0.0))
            V = np.maximum(V, intrinsic)

        if style == "barrier" and barrier is not None:
            V[S_i >= barrier] = 0.0

    return float(V[0])


