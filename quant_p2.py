def heston_mc(S, K, T, r, kappa, theta, xi, rho, v0,
              n_paths=10000, n_steps=252,
              option_type="call",
              antithetic=True,
              control_variate=True,
              seed=42):
    """
    Heston Monte Carlo pricer with variance reduction.

    Euler-Maruyama discretisation:
      S_{t+1} = S_t * exp((r - v_t/2)*dt + sqrt(v_t)*sqrt(dt)*Z1)
      v_{t+1} = v_t + κ(θ-v_t)*dt + ξ*sqrt(v_t)*sqrt(dt)*Z2
      corr(Z1,Z2) = ρ  via Cholesky: Z2 = ρ*Z1 + sqrt(1-ρ²)*Z_ind

    Variance reduction:
      Antithetic variates : run -Z paths, average with +Z paths
      Control variates    : use BSM price as control

    Parameters
    ----------
    antithetic      : bool — use antithetic variates
    control_variate : bool — use BSM control variate

    Returns
    -------
    price     : float — option price
    std_error : float — MC standard error
    paths_S   : array — sample stock paths (for plotting)
    """
    np.random.seed(seed)
    dt        = T / n_steps
    sqrt_dt   = np.sqrt(dt)
    sqrt_1rho = np.sqrt(1 - rho**2)

    def simulate_paths(Z1, Z2):
        """ Simulate S and v paths given correlated normals. """
        S_paths = np.zeros((n_paths, n_steps + 1))
        v_paths = np.zeros((n_paths, n_steps + 1))
        S_paths[:, 0] = S
        v_paths[:, 0] = v0

        for t in range(n_steps):
            v_t = v_paths[:, t]
            S_t = S_paths[:, t]

            # Full truncation: variance cannot go negative
            v_pos = np.maximum(v_t, 0)

            # Correlated Brownian motions via Cholesky
            dW1 = Z1[:, t] * sqrt_dt
            dW2 = (rho * Z1[:, t] + sqrt_1rho * Z2[:, t]) * sqrt_dt

            # Euler-Maruyama update
            S_paths[:, t+1] = S_t * np.exp(
                (r - 0.5 * v_pos) * dt + np.sqrt(v_pos) * dW1
            )
            v_paths[:, t+1] = np.maximum(
                v_t + kappa * (theta - v_pos) * dt
                + xi * np.sqrt(v_pos) * dW2,
                0  # Full truncation
            )
        return S_paths, v_paths

    # ── Generate random numbers ───────────────────────────────
    Z1 = np.random.standard_normal((n_paths, n_steps))
    Z2 = np.random.standard_normal((n_paths, n_steps))

    # ── Simulate paths ────────────────────────────────────────
    S_paths, v_paths = simulate_paths(Z1, Z2)
    S_T = S_paths[:, -1]

    # ── Terminal payoffs ──────────────────────────────────────
    if option_type == "call":
        payoffs = np.maximum(S_T - K, 0)
    else:
        payoffs = np.maximum(K - S_T, 0)

    # ── Antithetic variates ───────────────────────────────────
    if antithetic:
        S_paths_anti, _ = simulate_paths(-Z1, -Z2)
        S_T_anti = S_paths_anti[:, -1]
        if option_type == "call":
            payoffs_anti = np.maximum(S_T_anti - K, 0)
        else:
            payoffs_anti = np.maximum(K - S_T_anti, 0)
        payoffs = (payoffs + payoffs_anti) / 2.0

    # Discount
    discounted = np.exp(-r * T) * payoffs

    # ── Control variates ──────────────────────────────────────
    if control_variate:
        # Use average vol across paths as control sigma
        avg_var   = np.mean(v_paths, axis=1)
        avg_sigma = np.sqrt(np.maximum(avg_var, 1e-8))

        bsm_mc_prices = np.array([
            bsm_price(S, K, T, r, sig, option_type)[0]
            for sig in avg_sigma[:200]   # Sample 200 for speed
        ])
        bsm_analytical, _, _ = bsm_price(S, K, T, r,
                                          np.sqrt(theta), option_type)
        control_mean  = np.mean(bsm_mc_prices)
        beta          = np.cov(discounted[:200],
                               bsm_mc_prices)[0,1] / np.var(bsm_mc_prices)
        discounted    = (discounted[:200]
                         - beta * (bsm_mc_prices - bsm_analytical))

    price     = float(np.mean(discounted))
    std_error = float(np.std(discounted) / np.sqrt(len(discounted)))

    return price, std_error, S_paths[:50]   # Return 50 sample paths


